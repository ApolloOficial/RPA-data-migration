CREATE OR REPLACE FUNCTION fn_string_health_score(
    p_string_id uuid,
    p_window_days integer DEFAULT 7,
    p_as_of timestamptz DEFAULT CURRENT_TIMESTAMP,
    OUT health_score numeric(5,2),
    OUT sibling_ratio numeric(6,4),
    OUT nominal_ratio numeric(6,4),
    OUT warning_penalty numeric(5,2)
)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_inverter uuid;
    v_nominal  numeric;
    v_peak     numeric;
    v_since    timestamptz := p_as_of - make_interval(days => p_window_days);
BEGIN
    SELECT inverter_id, nominal_power_wp INTO v_inverter, v_nominal FROM vw_string_capacity WHERE string_id = p_string_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'String % não encontrada', p_string_id; END IF;
    warning_penalty := 0;
    IF v_nominal IS NULL OR v_nominal = 0 THEN RETURN; END IF;

    SELECT percentile_cont(0.95) WITHIN GROUP (ORDER BY m.power_w) INTO v_peak
      FROM string_performance_measurement m
     WHERE m.string_id = p_string_id AND m.measured_at > v_since AND m.measured_at <= p_as_of;
    IF v_peak IS NULL THEN RETURN; END IF;
    nominal_ratio := LEAST(1.0, v_peak / v_nominal);

    WITH siblings AS (
        SELECT c.string_id, c.nominal_power_wp
          FROM vw_string_capacity c JOIN string s ON s.id = c.string_id
         WHERE c.inverter_id = v_inverter AND c.nominal_power_wp > 0
           AND (s.status IN ('ATIVA', 'MANUTENCAO') OR s.id = p_string_id)
    ), win AS (
        SELECT m.string_id, m.measured_at, m.power_w / sb.nominal_power_wp AS norm
          FROM string_performance_measurement m JOIN siblings sb ON sb.string_id = m.string_id
         WHERE m.measured_at > v_since AND m.measured_at <= p_as_of
    ), agg AS (
        SELECT measured_at, sum(norm) AS total, count(*) AS n FROM win GROUP BY measured_at
    )
    SELECT avg(LEAST(1.0, w.norm / ((a.total - w.norm) / (a.n - 1)))) INTO sibling_ratio
      FROM win w JOIN agg a ON a.measured_at = w.measured_at
     WHERE w.string_id = p_string_id AND a.n > 1 AND a.total - w.norm > 0;

    SELECT COALESCE(sum(CASE w.severity WHEN 'CRITICA' THEN 12 WHEN 'ALTA' THEN 6 WHEN 'MEDIA' THEN 3 ELSE 0 END), 0)
      INTO warning_penalty
      FROM warning w JOIN vw_warning_target t ON t.warning_id = w.id
     WHERE t.string_id = p_string_id
       AND w.type <> 'EFICIENCIA_BAIXA'
       AND w.generation_dt <= p_as_of
       AND (w.resolved_at IS NULL OR w.resolved_at > p_as_of);

    health_score := GREATEST(0, LEAST(100, round(
        100 * CASE WHEN sibling_ratio IS NULL THEN nominal_ratio ELSE 0.6 * sibling_ratio + 0.4 * nominal_ratio END
        - warning_penalty, 2)));
END;
$$;

CREATE OR REPLACE FUNCTION fn_relocation_candidates(p_company_id bigint, p_threshold numeric DEFAULT 70)
RETURNS TABLE (string_id uuid, string_code varchar, inverter_code varchar, company_unit_id uuid, unit_name varchar,
               manufacturer varchar, model varchar, installed_panels bigint, nominal_power_wp numeric,
               health_score numeric, health_calculated_at timestamptz, ranking bigint)
LANGUAGE sql STABLE AS $$
    WITH candidates AS (
        SELECT s.id, s.code, i.code AS inverter_code, cu.id AS unit_id, cu.name AS unit_name, pm.manufacturer, pm.model,
               c.installed_panels, c.nominal_power_wp, h.health_score, h.calculated_at
          FROM string s
          JOIN inverter i ON i.id = s.inverter_id
          JOIN company_unit cu ON cu.id = i.company_unit_id
          JOIN panel_model pm ON pm.id = s.panel_model_id
          JOIN vw_string_capacity c ON c.string_id = s.id
          JOIN vw_string_current_health h ON h.string_id = s.id
         WHERE cu.company_id = p_company_id AND s.status IN ('ATIVA', 'MANUTENCAO') AND h.health_score < p_threshold
    )
    SELECT id, code, inverter_code, unit_id, unit_name, manufacturer, model, installed_panels, nominal_power_wp,
           health_score, calculated_at, dense_rank() OVER (ORDER BY health_score)
      FROM candidates
     ORDER BY health_score, code;
$$;

CREATE OR REPLACE PROCEDURE pr_register_inverter(
    p_operator_id uuid,
    p_payload jsonb,
    INOUT p_inverter_id uuid DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
    v_unit      uuid;
    v_model_id  bigint;
    v_string    jsonb;
    v_string_id uuid;
    v_panel     jsonb;
    v_seq       integer := 0;
    v_count     integer;
BEGIN
    IF fn_role_of(p_operator_id) IS DISTINCT FROM 'OPERADOR' THEN
        RAISE EXCEPTION 'Somente um operador ativo cadastra inversor, strings e placas';
    END IF;
    SELECT company_unit_id INTO v_unit FROM employee WHERE id = p_operator_id;
    v_model_id := (p_payload ->> 'inverter_model_id')::bigint;
    IF jsonb_typeof(p_payload -> 'strings') IS DISTINCT FROM 'array' OR jsonb_array_length(p_payload -> 'strings') = 0 THEN
        RAISE EXCEPTION 'Informe ao menos uma string do inversor';
    END IF;

    INSERT INTO inverter (company_unit_id, inverter_model_id, code, serial_number, installed_at, created_by)
    VALUES (v_unit, v_model_id, p_payload ->> 'code', btrim(p_payload ->> 'serial_number'),
            (p_payload ->> 'installed_at')::date, p_operator_id)
    RETURNING id INTO p_inverter_id;

    FOR v_string IN SELECT value FROM jsonb_array_elements(p_payload -> 'strings') ORDER BY
        (value ->> 'mppt_number')::int, (value ->> 'entry_number')::int
    LOOP
        v_seq := v_seq + 1;
        v_count := jsonb_array_length(v_string -> 'panels');
        IF v_count IS NULL OR v_count = 0 THEN
            RAISE EXCEPTION 'A string na posição MPPT %/entrada % não tem placas', v_string ->> 'mppt_number', v_string ->> 'entry_number';
        END IF;
        INSERT INTO string (inverter_id, mppt_number, entry_number, code, panel_model_id, invoice_number,
                            acquisition_dt, unit_cost, purchased_qty, created_by)
        VALUES (p_inverter_id, (v_string ->> 'mppt_number')::smallint, (v_string ->> 'entry_number')::smallint,
                'STR-' || lpad(v_seq::text, 3, '0'), (v_string ->> 'panel_model_id')::bigint,
                btrim(v_string ->> 'invoice_number'), (v_string ->> 'acquisition_dt')::date,
                (v_string ->> 'unit_cost')::numeric, v_count, p_operator_id)
        RETURNING id INTO v_string_id;
        FOR v_panel IN SELECT value FROM jsonb_array_elements(v_string -> 'panels') LOOP
            INSERT INTO panel (string_id, serial_number, barcode)
            VALUES (v_string_id, btrim(v_panel ->> 'serial_number'), btrim(v_panel ->> 'barcode'));
        END LOOP;
    END LOOP;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_activate_panel(
    p_barcode varchar,
    p_technician_id uuid,
    p_installation_dt date DEFAULT CURRENT_DATE
)
LANGUAGE plpgsql AS $$
DECLARE
    v_panel     panel%ROWTYPE;
    v_unit      uuid;
    v_installed date;
BEGIN
    IF fn_role_of(p_technician_id) IS DISTINCT FROM 'TECNICO' THEN
        RAISE EXCEPTION 'Somente um técnico ativo ativa placas';
    END IF;
    SELECT * INTO v_panel FROM panel WHERE barcode = btrim(p_barcode) FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Código de barras % não cadastrado pelo operador', p_barcode; END IF;
    SELECT i.company_unit_id, i.installed_at INTO v_unit, v_installed
      FROM string s JOIN inverter i ON i.id = s.inverter_id WHERE s.id = v_panel.string_id;
    IF v_unit IS DISTINCT FROM (SELECT company_unit_id FROM employee WHERE id = p_technician_id) THEN
        RAISE EXCEPTION 'A placa % pertence a outra filial', v_panel.serial_number;
    END IF;
    IF v_panel.operating_stats <> 'EM_ESTOQUE' THEN
        RAISE EXCEPTION 'A placa % já está %', v_panel.serial_number, v_panel.operating_stats;
    END IF;
    IF p_installation_dt > CURRENT_DATE OR p_installation_dt < v_installed THEN
        RAISE EXCEPTION 'Data de instalação deve estar entre a instalação do inversor (%) e hoje', v_installed;
    END IF;

    UPDATE panel SET operating_stats = 'OPERACIONAL', installation_dt = p_installation_dt,
                     activated_at = p_installation_dt + time '12:00', updated_at = p_installation_dt + time '12:00'
     WHERE id = v_panel.id;

    UPDATE string SET status = 'ATIVA', updated_at = CURRENT_TIMESTAMP
     WHERE id = v_panel.string_id AND status = 'EM_ESTOQUE'
       AND NOT EXISTS (SELECT 1 FROM panel WHERE string_id = v_panel.string_id AND operating_stats = 'EM_ESTOQUE');
END;
$$;

CREATE OR REPLACE PROCEDURE pr_deactivate_panel(
    p_barcode varchar,
    p_technician_id uuid,
    p_reason text
)
LANGUAGE plpgsql AS $$
DECLARE
    v_panel panel%ROWTYPE;
BEGIN
    IF fn_role_of(p_technician_id) IS DISTINCT FROM 'TECNICO' THEN
        RAISE EXCEPTION 'Somente um técnico ativo desativa placas';
    END IF;
    SELECT * INTO v_panel FROM panel WHERE barcode = btrim(p_barcode) FOR UPDATE;
    IF NOT FOUND OR v_panel.operating_stats IN ('EM_ESTOQUE', 'INATIVO') THEN
        RAISE EXCEPTION 'Placa % inexistente ou não instalada', p_barcode;
    END IF;
    UPDATE panel SET operating_stats = 'INATIVO', deactivated_at = CURRENT_TIMESTAMP, updated_at = CURRENT_TIMESTAMP
     WHERE id = v_panel.id;
    UPDATE panel_status_history SET reason = p_reason
     WHERE id = (SELECT max(id) FROM panel_status_history WHERE panel_id = v_panel.id);
END;
$$;

CREATE OR REPLACE PROCEDURE pr_ingest_string_measurement(
    p_inverter_serial varchar,
    p_mppt_number smallint,
    p_entry_number smallint,
    p_measured_at timestamptz,
    p_power_w numeric,
    p_voltage_v numeric DEFAULT NULL,
    p_current_a numeric DEFAULT NULL,
    p_generated_energy_kwh numeric DEFAULT NULL,
    p_fault_code varchar DEFAULT NULL,
    p_data_source varchar DEFAULT 'SENSOR'
)
LANGUAGE plpgsql AS $$
DECLARE
    v_string_id uuid;
BEGIN
    SELECT s.id INTO v_string_id
      FROM string s JOIN inverter i ON i.id = s.inverter_id
     WHERE i.serial_number = p_inverter_serial AND s.mppt_number = p_mppt_number AND s.entry_number = p_entry_number
