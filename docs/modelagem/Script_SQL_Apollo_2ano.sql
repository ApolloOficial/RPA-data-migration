           generated_energy_kwh = EXCLUDED.generated_energy_kwh, fault_code = EXCLUDED.fault_code,
           data_source = EXCLUDED.data_source;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_recalculate_string_health(
    p_company_unit_id uuid DEFAULT NULL,
    p_window_days integer DEFAULT 7,
    p_threshold numeric DEFAULT 70,
    p_as_of timestamptz DEFAULT CURRENT_TIMESTAMP
)
LANGUAGE plpgsql AS $$
DECLARE
    v_string record;
    v_calc   record;
BEGIN
    FOR v_string IN
        SELECT s.id, s.code, i.code AS inverter_code
          FROM string s JOIN inverter i ON i.id = s.inverter_id
         WHERE s.status IN ('ATIVA', 'MANUTENCAO')
           AND (p_company_unit_id IS NULL OR i.company_unit_id = p_company_unit_id)
    LOOP
        SELECT * INTO v_calc FROM fn_string_health_score(v_string.id, p_window_days, p_as_of);
        CONTINUE WHEN v_calc.health_score IS NULL;

        INSERT INTO string_health_history (string_id, calculated_at, window_days, sibling_ratio, nominal_ratio, warning_penalty, health_score)
        VALUES (v_string.id, p_as_of, p_window_days, v_calc.sibling_ratio, v_calc.nominal_ratio, v_calc.warning_penalty, v_calc.health_score)
        ON CONFLICT (string_id, calculated_at) DO UPDATE
           SET window_days = EXCLUDED.window_days, sibling_ratio = EXCLUDED.sibling_ratio, nominal_ratio = EXCLUDED.nominal_ratio,
               warning_penalty = EXCLUDED.warning_penalty, health_score = EXCLUDED.health_score;

        IF v_calc.health_score < p_threshold THEN
            IF NOT EXISTS (SELECT 1 FROM warning WHERE string_id = v_string.id AND type = 'EFICIENCIA_BAIXA' AND status <> 'RESOLVIDO') THEN
                INSERT INTO warning (string_id, type, severity, status, message, generation_dt)
                VALUES (v_string.id, 'EFICIENCIA_BAIXA',
                        CASE WHEN v_calc.health_score < 50 THEN 'CRITICA' WHEN v_calc.health_score < 60 THEN 'ALTA' ELSE 'MEDIA' END,
                        'ATIVO',
                        format('Saúde da string %s do inversor %s em %s%% (limiar %s%%)',
                               v_string.code, v_string.inverter_code, v_calc.health_score, p_threshold),
                        p_as_of);
            END IF;
        ELSE
            UPDATE warning w SET status = 'RESOLVIDO', resolved_at = GREATEST(p_as_of, w.generation_dt)
             WHERE w.string_id = v_string.id AND w.type = 'EFICIENCIA_BAIXA' AND w.status = 'ATIVO'
               AND NOT EXISTS (SELECT 1 FROM maintenance_register mr WHERE mr.warning_id = w.id);
        END IF;
    END LOOP;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_report_panel_issue(
    p_barcode varchar,
    p_technician_id uuid,
    p_type varchar,
    p_severity varchar,
    p_message text,
    INOUT p_warning_id bigint DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
    v_panel_id bigint;
BEGIN
    IF fn_role_of(p_technician_id) IS DISTINCT FROM 'TECNICO' THEN
        RAISE EXCEPTION 'Somente um técnico ativo registra relato de campo';
    END IF;
    SELECT p.id INTO v_panel_id
      FROM panel p JOIN string s ON s.id = p.string_id JOIN inverter i ON i.id = s.inverter_id
     WHERE p.barcode = btrim(p_barcode)
       AND i.company_unit_id = (SELECT company_unit_id FROM employee WHERE id = p_technician_id);
    IF NOT FOUND THEN RAISE EXCEPTION 'Placa % não encontrada na filial do técnico', p_barcode; END IF;
    INSERT INTO warning (panel_id, type, severity, status, message, reported_by)
    VALUES (v_panel_id, upper(p_type), upper(p_severity), 'ATIVO', p_message, p_technician_id)
    RETURNING id INTO p_warning_id;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_open_maintenance(
    p_warning_id bigint,
    p_operator_id uuid,
    p_technician_id uuid,
    p_maintenance_type_id bigint,
    p_due_date timestamptz DEFAULT NULL,
    p_estimated_cost numeric DEFAULT NULL,
    p_parent_maintenance_id bigint DEFAULT NULL,
    INOUT p_maintenance_id bigint DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
    v_warning   warning%ROWTYPE;
    v_string_id uuid;
BEGIN
    SELECT * INTO v_warning FROM warning WHERE id = p_warning_id FOR UPDATE;
    IF NOT FOUND OR v_warning.status <> 'ATIVO' THEN
        RAISE EXCEPTION 'Alerta % inexistente ou já tratado', p_warning_id;
    END IF;
    SELECT string_id INTO v_string_id FROM vw_warning_target WHERE warning_id = p_warning_id;

    INSERT INTO maintenance_register (parent_maintenance_id, warning_id, maintenance_type_id, technician_id, created_by, due_date, estimated_cost)
    VALUES (p_parent_maintenance_id, p_warning_id, p_maintenance_type_id, p_technician_id, p_operator_id, p_due_date, p_estimated_cost)
    RETURNING id INTO p_maintenance_id;

    UPDATE warning SET status = 'RECONHECIDO' WHERE id = p_warning_id;
    UPDATE string SET status = 'MANUTENCAO', updated_at = CURRENT_TIMESTAMP WHERE id = v_string_id AND status = 'ATIVA';
    UPDATE panel SET operating_stats = 'MANUTENCAO', updated_at = CURRENT_TIMESTAMP
     WHERE operating_stats = 'OPERACIONAL'
       AND ((v_warning.panel_id IS NOT NULL AND id = v_warning.panel_id)
            OR (v_warning.panel_id IS NULL AND string_id = v_string_id));
END;
$$;

CREATE OR REPLACE PROCEDURE pr_start_maintenance(p_maintenance_id bigint, p_technician_id uuid)
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE maintenance_register SET maintenance_status = 'EM_ANDAMENTO', technician_id = p_technician_id
     WHERE id = p_maintenance_id AND maintenance_status = 'ABERTA';
    IF NOT FOUND THEN RAISE EXCEPTION 'OS % não está aberta', p_maintenance_id; END IF;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_release_after_maintenance(p_maintenance_id bigint)
LANGUAGE plpgsql AS $$
DECLARE
    v_string_id uuid;
    v_panel_id  bigint;
BEGIN
    SELECT t.string_id, w.panel_id INTO v_string_id, v_panel_id
      FROM maintenance_register mr JOIN warning w ON w.id = mr.warning_id JOIN vw_warning_target t ON t.warning_id = w.id
     WHERE mr.id = p_maintenance_id;
    IF EXISTS (SELECT 1 FROM maintenance_register mr JOIN vw_warning_target t ON t.warning_id = mr.warning_id
                WHERE t.string_id = v_string_id AND mr.id <> p_maintenance_id AND mr.maintenance_status IN ('ABERTA', 'EM_ANDAMENTO')) THEN
        UPDATE panel SET operating_stats = 'OPERACIONAL', updated_at = CURRENT_TIMESTAMP
         WHERE id = v_panel_id AND operating_stats = 'MANUTENCAO';
    ELSE
        UPDATE panel SET operating_stats = 'OPERACIONAL', updated_at = CURRENT_TIMESTAMP
         WHERE string_id = v_string_id AND operating_stats = 'MANUTENCAO';
        UPDATE string SET status = 'ATIVA', updated_at = CURRENT_TIMESTAMP WHERE id = v_string_id AND status = 'MANUTENCAO';
    END IF;
END;
$$;

CREATE OR REPLACE PROCEDURE pr_complete_maintenance(
    p_maintenance_id bigint,
    p_technician_id uuid,
    p_technical_report text,
    p_labor_cost numeric DEFAULT NULL
)
LANGUAGE plpgsql AS $$
DECLARE
    v_warning_id bigint;
BEGIN
    IF fn_role_of(p_technician_id) IS DISTINCT FROM 'TECNICO' THEN
        RAISE EXCEPTION 'Somente um técnico ativo conclui OS';
    END IF;
    UPDATE maintenance_register
       SET technician_id = p_technician_id, technical_report = p_technical_report, labor_cost = p_labor_cost,
           maintenance_status = 'CONCLUIDA', concluded_at = CURRENT_TIMESTAMP
     WHERE id = p_maintenance_id AND maintenance_status IN ('ABERTA', 'EM_ANDAMENTO')
    RETURNING warning_id INTO v_warning_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'OS ativa % não encontrada', p_maintenance_id; END IF;
    UPDATE warning SET status = 'RESOLVIDO', resolved_at = GREATEST(CURRENT_TIMESTAMP, generation_dt) WHERE id = v_warning_id;
    CALL pr_release_after_maintenance(p_maintenance_id);
END;
$$;

CREATE OR REPLACE PROCEDURE pr_cancel_maintenance(
    p_maintenance_id bigint,
    p_operator_id uuid,
    p_reason text
)
LANGUAGE plpgsql AS $$
DECLARE
    v_warning_id bigint;
    v_company    bigint;
BEGIN
    IF fn_role_of(p_operator_id) IS DISTINCT FROM 'OPERADOR' THEN
        RAISE EXCEPTION 'Somente um operador ativo cancela OS';
    END IF;
    SELECT mr.warning_id, t.company_id INTO v_warning_id, v_company
      FROM maintenance_register mr JOIN vw_warning_target t ON t.warning_id = mr.warning_id
     WHERE mr.id = p_maintenance_id AND mr.maintenance_status IN ('ABERTA', 'EM_ANDAMENTO');
    IF NOT FOUND THEN RAISE EXCEPTION 'OS ativa % não encontrada', p_maintenance_id; END IF;
    IF v_company IS DISTINCT FROM fn_company_of_employee(p_operator_id) THEN
        RAISE EXCEPTION 'OS de outra empresa';
    END IF;
    UPDATE maintenance_register
       SET maintenance_status = 'CANCELADA', cancelled_by = p_operator_id, cancelled_at = CURRENT_TIMESTAMP,
           cancellation_reason = p_reason
     WHERE id = p_maintenance_id;
    UPDATE warning SET status = 'ATIVO' WHERE id = v_warning_id AND status = 'RECONHECIDO';
    CALL pr_release_after_maintenance(p_maintenance_id);
END;
$$;

CREATE OR REPLACE PROCEDURE pr_register_access(
    p_email varchar,
    p_session_id uuid,
    p_ip_address inet,
    p_access_status varchar
)
LANGUAGE plpgsql AS $$
DECLARE
    v_employee uuid;
BEGIN
    SELECT id INTO v_employee FROM employee WHERE lower(email) = lower(btrim(p_email));
    IF v_employee IS NULL AND upper(p_access_status) = 'SUCESSO' THEN
        RAISE EXCEPTION 'Login com sucesso exige funcionário cadastrado';
    END IF;
