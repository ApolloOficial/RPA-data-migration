    IF NEW.parent_maintenance_id IS NOT NULL AND v_company IS DISTINCT FROM (
        SELECT t.company_id FROM maintenance_register p JOIN vw_warning_target t ON t.warning_id = p.warning_id
         WHERE p.id = NEW.parent_maintenance_id) THEN
        RAISE EXCEPTION 'A OS de origem pertence a outra empresa';
    END IF;
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

