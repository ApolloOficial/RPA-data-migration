CREATE OR REPLACE FUNCTION fn_consume_maintenance_part()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_status    varchar;
    v_unit      uuid;
    v_available integer;
    v_cost      numeric(12,2);
BEGIN
    SELECT mr.maintenance_status, t.company_unit_id INTO v_status, v_unit
      FROM maintenance_register mr JOIN vw_warning_target t ON t.warning_id = mr.warning_id
     WHERE mr.id = NEW.maintenance_id;
    IF v_status NOT IN ('ABERTA', 'EM_ANDAMENTO') THEN
        RAISE EXCEPTION 'Peças só podem ser lançadas em OS aberta ou em andamento';
    END IF;
    SELECT available_qtt, unit_cost INTO v_available, v_cost
      FROM stock WHERE company_unit_id = v_unit AND part_id = NEW.part_id FOR UPDATE;
