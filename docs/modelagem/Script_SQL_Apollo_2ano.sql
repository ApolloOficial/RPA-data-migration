CREATE VIEW dm.vw_maintenance_chain AS
WITH RECURSIVE maintenance_tree AS (
    SELECT mr.id, mr.parent_maintenance_id, mr.warning_id, mr.maintenance_status, mr.opening_dt,
           1 AS chain_level, ARRAY[mr.id] AS path
      FROM maintenance_register mr WHERE mr.parent_maintenance_id IS NULL
    UNION ALL
    SELECT child.id, child.parent_maintenance_id, child.warning_id, child.maintenance_status, child.opening_dt,
           parent.chain_level + 1, parent.path || child.id
      FROM maintenance_register child JOIN maintenance_tree parent ON parent.id = child.parent_maintenance_id
     WHERE NOT child.id = ANY(parent.path)
)
SELECT t.*, w.string_id FROM maintenance_tree t JOIN vw_warning_target w ON w.warning_id = t.warning_id;

