CREATE VIEW dm.fact_string_daily_performance AS
WITH daily AS (
    SELECT m.string_id AS string_key, s.inverter_id AS inverter_key,
           (m.measured_at AT TIME ZONE 'America/Sao_Paulo')::date AS measurement_date,
           sum(m.generated_energy_kwh) AS generated_energy_kwh,
           max(m.power_w) AS peak_power_w,
           c.nominal_power_wp,
           round(max(m.power_w) / NULLIF(c.nominal_power_wp, 0), 4) AS peak_to_nominal_ratio,
           count(*) FILTER (WHERE m.fault_code IS NOT NULL) AS fault_count,
           count(*) AS measurement_count
      FROM string_performance_measurement m
      JOIN string s ON s.id = m.string_id
      JOIN vw_string_capacity c ON c.string_id = s.id
     GROUP BY m.string_id, s.inverter_id, (m.measured_at AT TIME ZONE 'America/Sao_Paulo')::date, c.nominal_power_wp
), analytic AS (
    SELECT d.*,
