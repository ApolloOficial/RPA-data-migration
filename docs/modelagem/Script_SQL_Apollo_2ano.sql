    END IF;
    UPDATE stock SET available_qtt = available_qtt - NEW.quantity, updated_at = CURRENT_TIMESTAMP
     WHERE company_unit_id = v_unit AND part_id = NEW.part_id;
    NEW.unit_cost := COALESCE(NEW.unit_cost, v_cost);
    RETURN NEW;
END;
$$;

