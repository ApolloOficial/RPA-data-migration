CREATE OR REPLACE FUNCTION fn_measurement_fault_warning()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.fault_code IS NOT NULL AND btrim(NEW.fault_code) <> ''
       AND (TG_OP = 'INSERT' OR OLD.fault_code IS DISTINCT FROM NEW.fault_code)
       AND NOT EXISTS (SELECT 1 FROM warning w WHERE w.string_id = NEW.string_id
                          AND w.type = 'FALHA_INVERSOR' AND w.status <> 'RESOLVIDO') THEN
        INSERT INTO warning (string_id, type, severity, status, message, generation_dt)
        VALUES (NEW.string_id, 'FALHA_INVERSOR', 'CRITICA', 'ATIVO',
                format('Inversor reportou o código de falha %s na leitura de %s', NEW.fault_code,
                       to_char(NEW.measured_at AT TIME ZONE 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI')),
                NEW.measured_at);
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_validate_maintenance()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_company bigint;
BEGIN
    SELECT company_id INTO v_company FROM vw_warning_target WHERE warning_id = NEW.warning_id;
    IF fn_role_of(NEW.technician_id) IS DISTINCT FROM 'TECNICO' THEN
        RAISE EXCEPTION 'O responsável pela OS deve ser um técnico ativo';
    END IF;
    IF TG_OP = 'INSERT' AND fn_role_of(NEW.created_by) IS DISTINCT FROM 'OPERADOR' THEN
        RAISE EXCEPTION 'Somente o operador abre OS';
    END IF;
