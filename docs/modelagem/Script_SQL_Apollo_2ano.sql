CREATE OR REPLACE FUNCTION fn_validate_employee()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_role         varchar;
    v_creator_role varchar;
    v_creator_unit uuid;
BEGIN
    SELECT name INTO v_role FROM roles WHERE id = NEW.role_id;
    IF v_role = 'GERENTE' THEN
        IF NEW.source_id IS NULL THEN
            RAISE EXCEPTION 'Gerente só é cadastrado pelo administrador no CRUD do 1º ano e chega pelo RPA';
        END IF;
    ELSE
        IF NEW.created_by IS NULL THEN
            RAISE EXCEPTION 'Analista, operador e técnico são cadastrados pelo gerente da filial';
        END IF;
        SELECT fn_role_of(NEW.created_by), company_unit_id INTO v_creator_role, v_creator_unit
          FROM employee WHERE id = NEW.created_by;
        IF v_creator_role IS DISTINCT FROM 'GERENTE' OR v_creator_unit IS DISTINCT FROM NEW.company_unit_id THEN
            RAISE EXCEPTION 'O cadastro deve ser feito por um gerente ativo da mesma filial';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_validate_inverter()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF fn_role_of(NEW.created_by) IS DISTINCT FROM 'OPERADOR'
       OR (SELECT company_unit_id FROM employee WHERE id = NEW.created_by) IS DISTINCT FROM NEW.company_unit_id THEN
        RAISE EXCEPTION 'Inversor só pode ser cadastrado por um operador ativo da própria filial';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_validate_string()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_unit       uuid;
    v_mppt_count smallint;
    v_per_mppt   smallint;
    v_code       varchar;
BEGIN
    SELECT i.company_unit_id, im.mppt_count, im.strings_per_mppt, i.code
      INTO v_unit, v_mppt_count, v_per_mppt, v_code
      FROM inverter i JOIN inverter_model im ON im.id = i.inverter_model_id
     WHERE i.id = NEW.inverter_id;
    IF NEW.mppt_number > v_mppt_count THEN
        RAISE EXCEPTION 'MPPT % fora do intervalo 1..% do inversor %', NEW.mppt_number, v_mppt_count, v_code;
    END IF;
    IF NEW.entry_number > v_per_mppt THEN
        RAISE EXCEPTION 'Entrada % fora do intervalo 1..% do MPPT', NEW.entry_number, v_per_mppt;
    END IF;
    IF TG_OP = 'INSERT' AND (fn_role_of(NEW.created_by) IS DISTINCT FROM 'OPERADOR'
       OR (SELECT company_unit_id FROM employee WHERE id = NEW.created_by) IS DISTINCT FROM v_unit) THEN
        RAISE EXCEPTION 'String só pode ser cadastrada por um operador ativo da filial do inversor';
    END IF;
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

