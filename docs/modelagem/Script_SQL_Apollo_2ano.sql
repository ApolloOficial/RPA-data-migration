CREATE VIEW dm.dim_date AS
WITH bounds AS (
    SELECT least(
               COALESCE((SELECT min(measured_at AT TIME ZONE 'America/Sao_Paulo')::date FROM string_performance_measurement), CURRENT_DATE),
               COALESCE((SELECT min(opening_dt AT TIME ZONE 'America/Sao_Paulo')::date FROM maintenance_register), CURRENT_DATE),
