    VALUES (v_employee, CASE WHEN v_employee IS NULL THEN lower(btrim(p_email)) END, p_session_id, p_ip_address, upper(p_access_status))
    ON CONFLICT (session_id) DO NOTHING;
END;
$$;

CREATE OR REPLACE PROCEDURE staging.pr_sync_legacy(p_load_batch_id bigint)
LANGUAGE plpgsql AS $$
DECLARE
    r            record;
    v_admin      bigint;
    v_company    bigint;
    v_segment    bigint;
    v_address    bigint;
    v_unit       uuid;
    v_role       bigint;
    v_total      integer;
BEGIN
    UPDATE staging.rpa_load_batch SET status = 'PROCESSING', started_at = CURRENT_TIMESTAMP
     WHERE id = p_load_batch_id AND status = 'RECEIVED';
    IF NOT FOUND THEN RAISE EXCEPTION 'Carga % indisponível para processamento', p_load_batch_id; END IF;

    FOR r IN SELECT * FROM staging.legacy_user WHERE load_batch_id = p_load_batch_id AND user_type = 'ADMINISTRADOR'
                AND processing_status = 'PENDING' ORDER BY source_id LOOP
        BEGIN
            INSERT INTO administrator (full_name, email, cpf, is_active, source_id, synced_at)
            VALUES (r.full_name, lower(r.email), r.cpf, r.is_active, r.source_id, CURRENT_TIMESTAMP)
            ON CONFLICT (source_id) DO UPDATE
               SET full_name = EXCLUDED.full_name, email = EXCLUDED.email, cpf = EXCLUDED.cpf,
                   is_active = EXCLUDED.is_active, synced_at = EXCLUDED.synced_at;
            UPDATE staging.legacy_user SET processing_status = 'PROCESSED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
        EXCEPTION WHEN OTHERS THEN
            UPDATE staging.legacy_user SET processing_status = 'FAILED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
            INSERT INTO staging.rpa_load_error (load_batch_id, source_record_key, error_message, source_payload)
            VALUES (p_load_batch_id, 'ADMINISTRADOR:' || r.source_id, SQLERRM, to_jsonb(r) - 'password_hash');
        END;
    END LOOP;

    FOR r IN SELECT * FROM staging.legacy_company WHERE load_batch_id = p_load_batch_id AND processing_status = 'PENDING' ORDER BY source_id LOOP
        BEGIN
            SELECT id INTO v_admin FROM administrator WHERE source_id = r.registered_by_source_id;
            IF v_admin IS NULL THEN RAISE EXCEPTION 'Administrador % não sincronizado', r.registered_by_source_id; END IF;
            INSERT INTO company (name, cnpj, contact_email, description, is_active, registered_by, source_id, synced_at)
            VALUES (r.name, r.cnpj, lower(r.contact_email), r.description, r.is_active, v_admin, r.source_id, CURRENT_TIMESTAMP)
            ON CONFLICT (source_id) DO UPDATE
               SET name = EXCLUDED.name, cnpj = EXCLUDED.cnpj, contact_email = EXCLUDED.contact_email,
                   description = EXCLUDED.description, is_active = EXCLUDED.is_active, synced_at = EXCLUDED.synced_at;
            UPDATE staging.legacy_company SET processing_status = 'PROCESSED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
        EXCEPTION WHEN OTHERS THEN
            UPDATE staging.legacy_company SET processing_status = 'FAILED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
            INSERT INTO staging.rpa_load_error (load_batch_id, source_record_key, error_message, source_payload)
            VALUES (p_load_batch_id, 'EMPRESA:' || r.source_id, SQLERRM, to_jsonb(r));
        END;
    END LOOP;

    FOR r IN SELECT * FROM staging.legacy_company_unit WHERE load_batch_id = p_load_batch_id AND processing_status = 'PENDING' ORDER BY source_id LOOP
        BEGIN
            SELECT id INTO v_company FROM company WHERE source_id = r.company_source_id;
            IF v_company IS NULL THEN RAISE EXCEPTION 'Empresa % não sincronizada', r.company_source_id; END IF;
            SELECT id INTO v_admin FROM administrator WHERE source_id = r.registered_by_source_id;
            IF v_admin IS NULL THEN RAISE EXCEPTION 'Administrador % não sincronizado', r.registered_by_source_id; END IF;

            INSERT INTO segment (name, source_id, synced_at) VALUES (r.segment_name, r.segment_source_id, CURRENT_TIMESTAMP)
            ON CONFLICT (source_id) DO UPDATE SET name = EXCLUDED.name, synced_at = EXCLUDED.synced_at
            RETURNING id INTO v_segment;

            SELECT address_id INTO v_address FROM company_unit WHERE source_id = r.source_id;
            IF v_address IS NULL THEN
                INSERT INTO address (street_name, number, additional_info, neighborhood, city, state, zip_code)
                VALUES (r.street_name, r.number, r.additional_info, r.neighborhood, r.city, upper(r.state), r.zip_code)
                RETURNING id INTO v_address;
            ELSE
                UPDATE address SET street_name = r.street_name, number = r.number, additional_info = r.additional_info,
                                   neighborhood = r.neighborhood, city = r.city, state = upper(r.state), zip_code = r.zip_code
                 WHERE id = v_address;
            END IF;

            INSERT INTO company_unit (company_id, segment_id, address_id, name, cnpj, email, phone, registered_by, is_active, source_id, synced_at)
            VALUES (v_company, v_segment, v_address, r.name, r.cnpj, lower(r.email), r.phone, v_admin, r.is_active, r.source_id, CURRENT_TIMESTAMP)
            ON CONFLICT (source_id) DO UPDATE
               SET company_id = EXCLUDED.company_id, segment_id = EXCLUDED.segment_id, name = EXCLUDED.name, cnpj = EXCLUDED.cnpj,
                   email = EXCLUDED.email, phone = EXCLUDED.phone, is_active = EXCLUDED.is_active, synced_at = EXCLUDED.synced_at;
            UPDATE staging.legacy_company_unit SET processing_status = 'PROCESSED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
        EXCEPTION WHEN OTHERS THEN
            UPDATE staging.legacy_company_unit SET processing_status = 'FAILED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
            INSERT INTO staging.rpa_load_error (load_batch_id, source_record_key, error_message, source_payload)
            VALUES (p_load_batch_id, 'FILIAL:' || r.source_id, SQLERRM, to_jsonb(r));
        END;
    END LOOP;

    SELECT id INTO v_role FROM roles WHERE name = 'GERENTE';
    FOR r IN SELECT * FROM staging.legacy_user WHERE load_batch_id = p_load_batch_id AND user_type = 'GERENTE'
                AND processing_status = 'PENDING' ORDER BY source_id LOOP
        BEGIN
            SELECT id INTO v_unit FROM company_unit WHERE source_id = r.company_unit_source_id;
            IF v_unit IS NULL THEN RAISE EXCEPTION 'Filial % não sincronizada', r.company_unit_source_id; END IF;
            SELECT id INTO v_admin FROM administrator WHERE source_id = r.registered_by_source_id;
            IF v_admin IS NULL THEN RAISE EXCEPTION 'Administrador % não sincronizado', r.registered_by_source_id; END IF;
            IF r.password_hash IS NULL OR r.password_hash !~ '^\$2[aby]\$' THEN
                RAISE EXCEPTION 'Senha do gerente não está em bcrypt (use crypt(senha, gen_salt(''bf'', 10)) no 1º ano)';
            END IF;
            INSERT INTO employee (full_name, email, password_hash, role_id, company_unit_id, is_active, registered_by, source_id, synced_at)
            VALUES (r.full_name, lower(r.email), r.password_hash, v_role, v_unit, r.is_active, v_admin, r.source_id, CURRENT_TIMESTAMP)
            ON CONFLICT (source_id) DO UPDATE
               SET full_name = EXCLUDED.full_name, email = EXCLUDED.email, password_hash = EXCLUDED.password_hash,
                   company_unit_id = EXCLUDED.company_unit_id, is_active = EXCLUDED.is_active, synced_at = EXCLUDED.synced_at;
            UPDATE company_unit cu SET responsible_employee_id = e.id
              FROM employee e WHERE e.source_id = r.source_id AND cu.id = v_unit AND cu.responsible_employee_id IS NULL;
            UPDATE staging.legacy_user SET processing_status = 'PROCESSED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
        EXCEPTION WHEN OTHERS THEN
            UPDATE staging.legacy_user SET processing_status = 'FAILED', processed_at = CURRENT_TIMESTAMP WHERE id = r.id;
            INSERT INTO staging.rpa_load_error (load_batch_id, source_record_key, error_message, source_payload)
            VALUES (p_load_batch_id, 'GERENTE:' || r.source_id, SQLERRM, to_jsonb(r) - 'password_hash');
        END;
    END LOOP;

    SELECT (SELECT count(*) FROM staging.legacy_user WHERE load_batch_id = p_load_batch_id)
         + (SELECT count(*) FROM staging.legacy_company WHERE load_batch_id = p_load_batch_id)
         + (SELECT count(*) FROM staging.legacy_company_unit WHERE load_batch_id = p_load_batch_id) INTO v_total;

    UPDATE staging.rpa_load_batch b
       SET total_records = v_total, processed_records = x.processed, failed_records = x.failed, finished_at = CURRENT_TIMESTAMP,
           status = CASE WHEN x.failed = 0 THEN 'COMPLETED' WHEN x.processed = 0 THEN 'FAILED' ELSE 'COMPLETED_WITH_ERRORS' END
      FROM (SELECT count(*) FILTER (WHERE processing_status = 'PROCESSED') AS processed,
                   count(*) FILTER (WHERE processing_status = 'FAILED') AS failed
              FROM (SELECT processing_status FROM staging.legacy_user WHERE load_batch_id = p_load_batch_id
                    UNION ALL SELECT processing_status FROM staging.legacy_company WHERE load_batch_id = p_load_batch_id
                    UNION ALL SELECT processing_status FROM staging.legacy_company_unit WHERE load_batch_id = p_load_batch_id) s) x
     WHERE b.id = p_load_batch_id;
END;
$$;

