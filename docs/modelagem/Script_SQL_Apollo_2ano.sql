CREATE VIEW vw_string_capacity AS
SELECT s.id AS string_id, s.inverter_id, pm.pmax_w,
       count(p.id) FILTER (WHERE p.operating_stats IN ('OPERACIONAL', 'MANUTENCAO', 'FALHA')) AS installed_panels,
       count(p.id) FILTER (WHERE p.operating_stats IN ('OPERACIONAL', 'MANUTENCAO', 'FALHA')) * pm.pmax_w AS nominal_power_wp
  FROM string s
  JOIN panel_model pm ON pm.id = s.panel_model_id
  LEFT JOIN panel p ON p.string_id = s.id
 GROUP BY s.id, s.inverter_id, pm.pmax_w;

CREATE VIEW vw_company_unit_capacity AS
SELECT cu.id AS company_unit_id, round(COALESCE(sum(c.nominal_power_wp), 0) / 1000.0, 2) AS kwp_total
  FROM company_unit cu
  LEFT JOIN inverter i ON i.company_unit_id = cu.id
  LEFT JOIN vw_string_capacity c ON c.inverter_id = i.id
 GROUP BY cu.id;

CREATE VIEW vw_string_current_health AS
SELECT DISTINCT ON (h.string_id) h.string_id, h.calculated_at, h.health_score, h.sibling_ratio, h.nominal_ratio, h.warning_penalty
  FROM string_health_history h
 ORDER BY h.string_id, h.calculated_at DESC;

CREATE VIEW vw_maintenance_order AS
SELECT mr.*, t.string_id, t.inverter_id, t.company_unit_id, w.severity AS priority, w.type AS warning_type,
       COALESCE(pc.parts_cost, 0) AS parts_cost,
       COALESCE(mr.labor_cost, 0) + COALESCE(pc.parts_cost, 0) AS total_cost,
       CASE WHEN mr.maintenance_status IN ('ABERTA', 'EM_ANDAMENTO') AND mr.due_date IS NOT NULL
             AND CURRENT_TIMESTAMP > mr.due_date THEN 'ATRASADA'
            ELSE mr.maintenance_status END AS calculated_status
  FROM maintenance_register mr
  JOIN warning w ON w.id = mr.warning_id
  JOIN vw_warning_target t ON t.warning_id = mr.warning_id
  LEFT JOIN (SELECT maintenance_id, sum(quantity * COALESCE(unit_cost, 0)) AS parts_cost
               FROM maintenance_part GROUP BY maintenance_id) pc ON pc.maintenance_id = mr.id;

